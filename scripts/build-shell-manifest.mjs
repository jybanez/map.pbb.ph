import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { posix } from 'node:path';
import { DEFAULT_COMPONENT_REGISTRY } from '../vendor/helpers/js/ui/ui.loader.js';
const sha = data => createHash('sha256').update(data).digest('hex');
const graph = JSON.parse(readFileSync('scripts/map-shell-graph.json', 'utf8'));
const paths = new Set(), components = new Set();
function resolve(parent, value) {
  const plain = value.split(/[?#]/)[0];
  if (!plain.startsWith('.')) throw new Error(`Expected local relative runtime dependency: ${parent}: ${value}`);
  const path = posix.normalize(posix.join(posix.dirname(parent), plain));
  if (path.startsWith('../') || !existsSync(path)) throw new Error(`Missing/outside shell dependency: ${path}`);
  return path;
}
function include(path) {
  if (paths.has(path)) return;
  if (!existsSync(path)) throw new Error(`Missing shell root: ${path}`);
  paths.add(path);
  // Loader registry paths are resolved only for declared application component roots.
  if (path === 'vendor/helpers/js/ui/ui.loader.js') return;
  if (!/\.(js|css)$/.test(path)) return;
  const source = readFileSync(path, 'utf8');
  const patterns = path.endsWith('.js') ? [/(?:from\s*|import\s*\(\s*|new URL\(\s*)["'](\.[^"']+)["']/g] : [/url\(\s*["']?(\.[^)'"\s]+)["']?\s*\)/g, /@import\s*["'](\.[^"']+)["']/g];
  for (const pattern of patterns) for (const match of source.matchAll(pattern)) {
    // SW script is independently installed and integrity-versioned by the manifest.
    if (match[1].split('?')[0].endsWith('map-shell-worker.js')) continue;
    const dependency = resolve(path, match[1]);
    if (statSync(dependency).isFile()) include(dependency);
  }
}
function component(name) {
  if (components.has(name)) return;
  const entry = DEFAULT_COMPONENT_REGISTRY[name];
  if (!entry) throw new Error(`Unknown Helper shell component: ${name}`);
  components.add(name);
  for (const dep of entry.deps || []) component(dep);
  if (entry.js) include(resolve('vendor/helpers/js/ui/ui.loader.js', entry.js));
  for (const css of entry.css || []) include(resolve('vendor/helpers/js/ui/ui.loader.js', css));
}
for (const root of graph.roots) include(root);
for (const name of graph.helperComponents) component(name);
// Fail when a newly named component in app modules is omitted from the declared graph.
for (const path of paths) if (path.startsWith('assets/') && path.endsWith('.js')) {
  for (const [, name] of readFileSync(path, 'utf8').matchAll(/["'](ui\.[a-z.]+)["']/g)) if (DEFAULT_COMPONENT_REGISTRY[name] && !components.has(name)) throw new Error(`Undeclared application Helper dependency: ${name}`);
}
const files = [...paths].sort().map(url => ({ url, sha256: sha(readFileSync(url)) }));
const version = sha(JSON.stringify(files) + sha(readFileSync('map-shell-worker.js'))).slice(0, 20);
const content = `// Generated by scripts/build-shell-manifest.mjs; do not edit.\nself.PBB_MAP_SHELL = ${JSON.stringify({ version, files }, null, 2)};\n`;
if (process.argv.includes('--check')) { if (readFileSync('shell-manifest.js', 'utf8') !== content) throw new Error('Shell manifest is stale; rebuild it'); }
else writeFileSync('shell-manifest.js', content);
console.log(`Shell ${version}: ${files.length} integrity-checked local assets, ${files.reduce((n, f) => n + readFileSync(f.url).byteLength, 0)} bytes; ${components.size} used Helper roots/dependencies`);
