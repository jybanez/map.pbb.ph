import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const sha = data => createHash('sha256').update(data).digest('hex');
function walk(dir) { return readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? walk(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`]); }
// Complete local runtime, including Helper lazy modules, CSS, person and direction workers.
// Library docs, integration/launcher assets and verification code are not runtime dependencies.
const paths = ['index.html', 'map.webmanifest', ...walk('assets'), ...walk('vendor')]
  .filter(path => !path.startsWith('assets/launcher/') && !/\.(md|txt|map)$/.test(path) && path !== 'vendor/manifest.json').sort();
const files = paths.map(url => ({ url, sha256: sha(readFileSync(url)) }));
const version = sha(JSON.stringify(files) + sha(readFileSync('map-shell-worker.js'))).slice(0, 20);
const content = `// Generated by scripts/build-shell-manifest.mjs; do not edit.\nself.PBB_MAP_SHELL = ${JSON.stringify({ version, files }, null, 2)};\n`;
if (process.argv.includes('--check')) { if (readFileSync('shell-manifest.js', 'utf8') !== content) throw new Error('Shell manifest is stale; rebuild it'); }
else writeFileSync('shell-manifest.js', content);
console.log(`Shell ${version}: ${files.length} integrity-checked local assets`);
